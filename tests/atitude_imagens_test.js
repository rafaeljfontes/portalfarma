const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../application/views/atitude-farmaceutica/inscricao_view.php'), 'utf8');
const handler = source.slice(source.indexOf('function handleFiles(files)'), source.indexOf('function renderPreviews()'));
const warnings = [];
const context = { selectedFiles: [], imageInput: { value: 'arquivo' }, renderPreviews() {}, Swal: { fire(data) { warnings.push(data); } } };
vm.createContext(context);
vm.runInContext(handler, context);
const imagem = { type: 'image/png', size: 1024 };
context.handleFiles(Array(7).fill(imagem));
assert.equal(context.selectedFiles.length, 5);
assert.equal(warnings.length, 1);
assert.equal(warnings[0].title, 'Limite de imagens');
context.handleFiles([imagem]);
assert.equal(context.selectedFiles.length, 5);
context.selectedFiles.splice(0, 1);
context.handleFiles([imagem]);
assert.equal(context.selectedFiles.length, 5);
context.selectedFiles.length = 0;
context.handleFiles([imagem, imagem]);
context.handleFiles([imagem, imagem, imagem, imagem]);
assert.equal(context.selectedFiles.length, 5);
context.selectedFiles.length = 0;
context.handleFiles([{ type: 'text/plain', size: 100 }, { type: 'image/png', size: 6 * 1024 * 1024 }, imagem]);
assert.equal(context.selectedFiles.length, 1);
assert.equal(context.imageInput.value, '');
console.log('OK: limite de 5, seleção cumulativa, remoção e arquivos inválidos.');
